import { expect, test } from "@playwright/test"

test("复式班评语按年级分开，断网仍能生成并确认", async ({ page }) => {
  await page.goto("/login")
  await page.getByLabel("账号").fill("demo-teacher-local")
  await page.getByLabel("口令").fill("Demo-Pass-0000")
  await page.getByRole("button", { name: "登录" }).click()
  await expect(page).toHaveURL(/\/m$/)
  const started = Date.now()
  await page.getByRole("button", { name: "阶段评语" }).click()
  await expect(page.getByText("当前是三年级的评语。本班其他年级请切换后查看。")).toBeVisible()
  await expect(page.getByText("下面是系统按已确认记录拼出的草稿，请老师改完再确认。没有确认，不会发给家长，也不会放进交接包。")).toBeVisible()
  await expect(page.getByText("一期不接通")).toBeVisible()
  await expect(page.getByRole("heading", { name: "演示生01" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "演示生02" })).toHaveCount(0)
  await page.getByRole("button", { name: "四年级" }).click()
  await expect(page.getByText("当前是四年级的评语。本班其他年级请切换后查看。")).toBeVisible()
  await expect(page.getByRole("heading", { name: "演示生02" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "演示生01" })).toHaveCount(0)
  await page.getByRole("button", { name: "三年级" }).click()
  await page.context().setOffline(true)
  await page.getByRole("button", { name: "生成草稿" }).click()
  await expect(page.locator("textarea")).toHaveValue(/朗读课文更流畅了/)
  await expect(page.locator("textarea")).toHaveValue(/遵守了课堂上事先说明的约定/)
  await expect(page.locator("textarea")).toHaveValue(/〔来源:learning:/)
  await expect(page.locator("textarea")).not.toHaveValue(/历史标签不进评语样本/)
  await expect(page.locator("textarea")).not.toHaveValue(/未确认不进评语样本/)
  await expect(page.locator("textarea")).not.toHaveValue(/能把段落按顺序说下来/)
  await expect(page.getByText("来源记录 learning")).toBeVisible()
  await page.getByRole("button", { name: "确认评语" }).click()
  await expect(page.getByText("已转入待补传")).toBeVisible()
  expect(Date.now() - started).toBeLessThan(120000)
  await page.context().setOffline(false)
  await page.reload()
  await page.getByRole("button", { name: "阶段评语" }).click()
  await expect(page.getByText("已确认，未发布")).toBeVisible()
  await expect(page.getByText("朗读课文更流畅了")).toBeVisible()
})
