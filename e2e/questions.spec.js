import { expect, test } from "@playwright/test"

test("未勾选原创授权不能保存自建题，菜单显示校本资源库", async ({ page }) => {
  await page.goto("/login")
  await page.getByLabel("账号").fill("demo-teacher-local")
  await page.getByLabel("口令").fill("Demo-Pass-0000")
  await page.getByRole("button", { name: "登录" }).click()
  await expect(page.getByText("校本资源库：老师自建题")).toBeVisible()
  await expect(page.getByText("课件：二期开放")).toBeVisible()
  await expect(page.getByText("教案：二期开放")).toBeVisible()
  await expect(page.getByText("校本教材上传：二期开放")).toBeVisible()
  await page.getByRole("button", { name: "老师自建题" }).click()
  await page.getByLabel("学科").selectOption({ label: "语文" })
  await page.getByLabel("年级").selectOption({ label: "三年级" })
  await page.getByLabel("教材版本").selectOption({ label: "人教版" })
  await page.getByLabel("知识点").selectOption({ label: "理解关键词句" })
  await page.getByLabel("题目").fill("把看到的句子抄写一遍")
  await page.getByRole("button", { name: "保存题目" }).click()
  await expect(page.getByText("未勾选「原创或已获授权」不能保存")).toBeVisible()
  await page.getByLabel("原创或已获授权").check()
  await page.getByRole("button", { name: "保存题目" }).click()
  await expect(page.getByText("已保存，默认本校可见")).toBeVisible()
  await expect(page.getByText("把看到的句子抄写一遍（本校，在用）")).toBeVisible()
  await expect(page.getByText("系统不自动按错题推送，也不生成变式题。")).toBeVisible()
  await page.getByLabel("选入练习单").check()
  await page.getByRole("button", { name: "生成练习单" }).click()
  await expect(page.getByRole("heading", { name: "练习单" })).toBeVisible()
  await expect(page.getByText("1. 把看到的句子抄写一遍")).toBeVisible()
})
