import { expect, test } from "@playwright/test"

test("给一个学生记一条不超过 3 次点击且不超过 5 秒", async ({ page }) => {
  await page.goto("/login")
  await page.getByLabel("账号").fill("demo-teacher-local")
  await page.getByLabel("口令").fill("Demo-Pass-0000")
  await page.getByRole("button", { name: "登录" }).click()
  await expect(page).toHaveURL(/\/m$/)
  await page.getByRole("button", { name: "记一笔" }).click()
  const started = Date.now()
  await page.getByRole("button", { name: "演示生01" }).click()
  await page.getByRole("button", { name: /遵守了课堂或活动中事先说明的一条约定/ }).click()
  await expect(page.getByText("点击 2 次")).toBeVisible()
  expect(Date.now() - started).toBeLessThan(5000)
  await expect(page.getByText("三年级 遵守了课堂或活动中事先说明的一条约定")).toBeVisible()
  await expect(page.getByText("总分")).toHaveCount(0)
  await expect(page.getByText("排名")).toHaveCount(0)
  await expect(page.getByText("朵")).toHaveCount(0)
  await expect(page.getByText("心理关怀")).toHaveCount(0)
  await page.getByRole("button", { name: "演示生01" }).click()
  await page.getByRole("button", { name: "演示生02" }).click()
  await page.getByRole("button", { name: /能说出并遵守一项校规/ }).click()
  await expect(page.getByText("四年级 能说出并遵守一项校规、课规或活动约定")).toBeVisible()
})
