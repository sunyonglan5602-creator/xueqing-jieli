import { expect, test } from "@playwright/test"

test("上次班级和科目会记住，切换只要一步，新账号先列出授权范围", async ({ page }) => {
  await page.goto("/login")
  await page.getByLabel("账号").fill("demo-teacher-local")
  await page.getByLabel("口令").fill("Demo-Pass-0000")
  await page.getByRole("button", { name: "登录" }).click()
  await expect(page).toHaveURL(/\/m$/)
  await page.evaluate(() => localStorage.clear())
  await page.getByRole("button", { name: "记学情" }).click()
  await expect(page.getByRole("button", { name: "演示一班 · 语文" })).toBeVisible()
  await expect(page.getByRole("button", { name: "演示一班 · 数学" })).toBeVisible()
  await page.getByRole("button", { name: "演示一班 · 语文" }).click()
  await page.getByRole("button", { name: "演示生01" }).click()
  await page.getByRole("button", { name: "理解关键词句" }).click()
  await page.getByRole("button", { name: "概念还没有讲清楚" }).click()
  await page.getByRole("button", { name: "保存" }).click()
  await expect(page.getByText(/已保存/)).toBeVisible()
  await page.getByRole("button", { name: "返回" }).click()
  const started = Date.now()
  await page.getByRole("button", { name: "记学情" }).click()
  await expect(page.getByText("演示一班 · 语文").first()).toBeVisible()
  await expect(page.getByRole("button", { name: "理解关键词句" })).toBeVisible()
  await page.getByRole("button", { name: "演示生01" }).click()
  await page.getByRole("button", { name: "理解关键词句" }).click()
  await page.getByRole("button", { name: "概念还没有讲清楚" }).click()
  await page.getByRole("button", { name: "保存" }).click()
  await expect(page.getByText("点击次数 5")).toBeVisible()
  expect(Date.now() - started).toBeLessThan(30_000)
  await expect(page.getByLabel("拍照（默认关闭）")).not.toBeChecked()
  await expect(page.locator("input[type=file]")).toHaveCount(0)
  await page.getByRole("button", { name: "演示一班 · 数学" }).click()
  await expect(page.getByRole("button", { name: "万以内的加减" })).toBeVisible()
  await expect(page.getByRole("button", { name: "理解关键词句" })).toHaveCount(0)
})
